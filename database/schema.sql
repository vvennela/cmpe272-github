CREATE TYPE user_role AS ENUM ('EMPLOYEE', 'ADMIN');
CREATE TYPE transit_route_type AS ENUM ('BART', 'BUS');
CREATE TYPE pickup_location_type AS ENUM ('COMPANY', 'BART', 'BUS_STOP');

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role user_role NOT NULL
);

CREATE TABLE shuttles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    longitude NUMERIC(10, 7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    latitude NUMERIC(9, 7) NOT NULL CHECK (latitude BETWEEN -90 AND 90)
);

CREATE TABLE pickup_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type pickup_location_type NOT NULL,
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    longitude NUMERIC(10, 7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    latitude NUMERIC(9, 7) NOT NULL CHECK (latitude BETWEEN -90 AND 90)
);

CREATE TABLE shuttle_routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shuttle_id BIGINT NOT NULL REFERENCES shuttles (id),
    pickup_location_id BIGINT NOT NULL REFERENCES pickup_locations (id),
    arrival_time TIME NOT NULL,
    departure_time TIME NOT NULL,
    route_type transit_route_type NOT NULL
);

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users (id),
    pickup_location_id BIGINT NOT NULL REFERENCES pickup_locations (id),
    shuttle_route_id BIGINT NOT NULL REFERENCES shuttle_routes (id)
);

CREATE TABLE route_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shuttle_route_id BIGINT NOT NULL REFERENCES shuttle_routes (id),
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    latitude NUMERIC(9, 7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(10, 7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    stop_order INTEGER NOT NULL CHECK (stop_order > 0),
    UNIQUE (shuttle_route_id, stop_order)
);